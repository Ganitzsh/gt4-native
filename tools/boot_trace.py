#!/usr/bin/env python3
"""The game's static call tree from its entry point: the order in which boot brings systems up.

Reads a gt4-decomp checkout (function bounds in build/functions.csv; names from config/symbol_addrs.txt,
config/adhoc_methods.txt, config/sdk_functions.tsv and the names of matched source files) and the user's
own executable. From --root, every function's `jal` targets are listed in the order they appear in its
body, breadth first to --depth. Calls made through pointers (virtual calls, callbacks) are not followed:
the tree is what the code says statically.

    python3 tools/boot_trace.py --decomp ../gt4-decomp [--root 00107F08] [--depth 3] [--out docs/BOOT_PATH.md]

The report holds function names, addresses and the decomp's source paths only: no game bytes.
"""
import argparse
import bisect
import csv
import os
import re
import struct
import subprocess

FUNC = re.compile(r"^func_([0-9A-Fa-f]{8})")


def text_segment(path):
    data = open(path, "rb").read()
    phoff, = struct.unpack_from("<I", data, 28)
    phentsize, phnum = struct.unpack_from("<HH", data, 42)
    for i in range(phnum):
        ptype, off, vaddr, _, filesz, _, flags, _ = struct.unpack_from("<8I", data, phoff + i * phentsize)
        if ptype == 1 and flags & 1:
            return vaddr, data[off:off + filesz]
    raise SystemExit("no executable PT_LOAD segment")


def names(decomp):
    """address -> (name, kind): kind is 'sdk', 'symbol' or 'source'."""
    out = {}
    for row in open(os.path.join(decomp, "config", "sdk_functions.tsv")):
        if not row.startswith("#") and row.strip():
            addr, name, member = row.rstrip("\n").split("\t")[:3]
            if name != ".text":
                out[int(addr, 16)] = (f"{name} ({member})", "sdk")
    for line in open(os.path.join(decomp, "config", "symbol_addrs.txt")):
        m = re.match(r"\s*([A-Za-z_$][\w$]*)\s*=\s*0x([0-9A-Fa-f]+)\s*;.*type:func", line)
        if m and not m.group(1).startswith("func_"):
            out.setdefault(int(m.group(2), 16), (m.group(1), "symbol"))
    adhoc = os.path.join(decomp, "config", "adhoc_methods.txt")
    if os.path.exists(adhoc):
        for line in open(adhoc):
            p = line.split()
            if len(p) == 3 and not line.startswith("#"):
                out.setdefault(int(p[2], 16), (f"{p[0]}::{p[1]}", "symbol"))
    return out


def sources(decomp):
    """address -> source path, for files named func_ADDR (others are named by the symbol tables)."""
    files = subprocess.run(["git", "-C", decomp, "ls-files", "src"], capture_output=True, text=True).stdout.split()
    out = {}
    for f in files:
        m = FUNC.match(os.path.basename(f))
        if m:
            out[int(m.group(1), 16)] = f
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--decomp", required=True)
    ap.add_argument("--elf", help="default: <decomp>/orig/SCUS-97328/CORE.GT4.elf")
    ap.add_argument("--root", default="00107F08")
    ap.add_argument("--depth", type=int, default=3)
    ap.add_argument("--out", default="docs/BOOT_PATH.md")
    a = ap.parse_args()
    starts = sorted(int(r["address"], 16) for r in csv.DictReader(open(os.path.join(a.decomp, "build", "functions.csv"))))
    base, text = text_segment(a.elf or os.path.join(a.decomp, "orig", "SCUS-97328", "CORE.GT4.elf"))
    named, src = names(a.decomp), sources(a.decomp)

    def callees(addr):
        i = bisect.bisect_left(starts, addr)
        end = starts[i + 1] if i + 1 < len(starts) else base + len(text)
        seen, out = set(), []
        for pc in range(addr, end, 4):
            word, = struct.unpack_from("<I", text, pc - base)
            if word >> 26 == 3:
                t = ((pc + 4) & 0xF0000000) | ((word & 0x03FFFFFF) << 2)
                if t not in seen:
                    seen.add(t)
                    out.append(t)
        return out

    def label(addr):
        n = named.get(addr)
        where = src.get(addr)
        text_ = f"`{addr:08X}`"
        if n:
            text_ += f" {n[0]}" + (" (SDK)" if n[1] == "sdk" and "(" not in n[0] else "")
        if where:
            text_ += f" — {where}"
        elif not n:
            text_ += " — no source yet"
        return text_

    root = int(a.root, 16)
    lines = ["# Boot path", "",
             f"Static call tree from `{root:08X}` (the game's `main`, called by crt0 after `_InitSys`), generated by",
             "`tools/boot_trace.py` from a gt4-decomp checkout and the user's own executable. Each function's direct",
             "calls are listed in the order they appear in its body; calls through pointers are not followed, and a",
             "function already expanded higher up is not expanded again.", ""]
    expanded = set()

    def walk(addr, depth, indent):
        lines.append(f"{'  ' * indent}- {label(addr)}")
        if depth >= a.depth or addr in expanded or named.get(addr, ("", ""))[1] == "sdk":
            return
        expanded.add(addr)
        for c in callees(addr):
            walk(c, depth + 1, indent + 1)

    walk(root, 0, 0)
    total = sum(1 for l in lines if l.lstrip().startswith("- "))
    missing = sum(1 for l in lines if "no source yet" in l)
    lines += ["", f"{total} entries; {missing} without a matched source yet."]
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    open(a.out, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{total} entries, {missing} without a source; wrote {a.out}")


if __name__ == "__main__":
    main()
