#!/usr/bin/env python3
"""Reproduce the reviewed native adaptation of the 0x174..0x188 accessor family.

Original files remain unmodified. Bodies are extracted verbatim except for the
one explicit same-object argument documented in docs/MILESTONE_4.md.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FUNCTIONS = (
    ('func_001465D8', 'src/gamedata/unit_0013B5F8/func_001465D8.cpp'),
    *((f'func_{address}', f'src/runtime/hArrayCompare/func_{address}.cpp') for address in (
        '005C9930', '005C9938', '005C9940', '005C9948', '005C9950', '005C9958',
        '005C9960', '005C9968', '005C99A8', '005C99B0', '005C99B8')),
    ('func_005C9970', 'src/runtime/hArrayCompare/func_005C9970.c'),
)


def generate(root=ROOT):
    upstream = root/'upstream/gt4'
    inventory = json.loads((upstream/'integration.json').read_text())
    expected = {r['path']: r['sha256'] for r in inventory['sources']}
    definitions, declarations, records = [], [], []
    for name, path in FUNCTIONS:
        imported = (upstream/path).read_bytes()
        prefix = (f"// Imported from gustavocanepa/gt4-decomp @ {inventory['upstream_commit']}\n"
                  f'// Original path: {path}\n').encode()
        if not imported.startswith(prefix):
            raise ValueError(f'wrong provenance: {path}')
        raw = imported[len(prefix):]
        digest = hashlib.sha256(raw).hexdigest()
        if digest != expected[path]:
            raise ValueError(f'upstream source changed; review required: {path}')
        text = raw.decode('utf-8')
        pattern = (r'\b(void|s32|f32)\s+' + name +
                   r'\s*\(([^)]*)\)\s*\{([^{}]*)\}')
        matches = list(re.finditer(pattern, text))
        if len(matches) != 1:
            raise ValueError(f'unsupported definition: {name}')
        result, params, original_body = matches[0].groups()
        params, replaced = re.subn(r'struct\s+\w+\s*\*\s*(\w+)', r'View* \1', params)
        if replaced != 1:
            raise ValueError(f'expected exactly one object parameter: {name}')
        body = original_body
        changes = []
        if name == 'func_005C9970':
            if body.count('func_001465D8()') != 1:
                raise ValueError('reviewed caller argument patch no longer applies')
            body = body.replace('func_001465D8()', 'func_001465D8(arg0)')
            changes.append('Pass unchanged PS2 a0 explicitly to func_001465D8')
        declaration = f'{result} {name}({params})'
        declarations.append(declaration+';')
        definitions.append(f'// {path}; original body with reviewed native argument adaptation.\n'
                           +declaration+' {'+body+'}\n')
        records.append(dict(path=path, symbol=name, sha256=digest,
                            original_body_sha256=hashlib.sha256(original_body.encode()).hexdigest(),
                            native_body_sha256=hashlib.sha256(body.encode()).hexdigest(),
                            body_changes=changes))
    generated = ('// Generated by tools/adapt_object_fields.py; do not edit.\n'
                 f"// Upstream: {inventory['upstream_commit']}\n"
                 '// Original sources retain the upstream MIT license; see THIRD_PARTY_NOTICES.md.\n'
                 'namespace gt4::native::object_fields::detail {\n'
                 'using s32 = std::int32_t;\nusing f32 = float;\n'
                 +'\n'.join(declarations)+'\n\n'+'\n'.join(definitions)+'}\n')
    report = dict(upstream_commit=inventory['upstream_commit'],
                  translation_unit='compat/abi/object_fields.cpp',
                  generated_include='compat/abi/object_fields_functions.inc',
                  generated_sha256=hashlib.sha256(generated.encode()).hexdigest(),
                  sources=records)
    return generated, json.dumps(report, indent=2)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, report = generate()
    for rel, content in [('compat/abi/object_fields_functions.inc', generated),
                         ('compat/abi/object_fields_sources.json', report)]:
        path = ROOT/rel
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'out of date: {rel}; run tools/adapt_object_fields.py')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print('13 reviewed upstream function adaptations verified' if args.check else '13 adaptations generated')


if __name__ == '__main__':
    main()
