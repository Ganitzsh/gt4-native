#!/usr/bin/env bash
# Build gt4_host for Linux, x86_64 or aarch64, needing no glibc newer than 2.35 (docs/modern/spikes/R4-link-across-fex.md:
# the host runs natively on the handheld, the game under Proton's Wine; tools/package_game.py --arch linux-ARCH
# packages it). On Ubuntu 24.04 (a WSL is enough; cmake, ninja-build, curl, binutils, python3), without root and
# without changing the system's packages:
#
#   bash tools/build_linux.sh [x86_64|aarch64] [extra CMake arguments]
#
# - The compiler is zig 0.17.1 (its clang, targeting ARCH-linux-gnu.2.35 with its own glibc stubs and libc++, so the
#   host needs only libc and libm), fetched once from ziglang.org and checked against its SHA-256.
# - SDL3's backends (X11, Wayland, PipeWire, PulseAudio, ALSA, udev, D-Bus) take headers, .pc files and the libraries'
#   names from a sysroot of Ubuntu noble's ARCH packages, fetched by a private apt (its own lists and cache): SDL loads
#   them all at run time, nothing links them. Wayland's protocol code is generated by wayland-scanner (libwayland-bin,
#   for this machine).
# - aarch64 is a cross build: the shaders are compiled by a glslang for this machine, the x86_64 build's (built here
#   first if needed) or GT4_GLSLANG_EXECUTABLE; no tests run (the binaries do not run here).
# Builds into build/host-linux-x64-Release or build/host-linux-arm64-Release (GT4_LINUX_BUILD overrides it, e.g. a
# folder in WSL's own file system, much faster than /mnt/c); tools and sysroots in GT4_LINUX_TOOLS (default
# ~/.cache/gt4-native/linux-tools).
set -euo pipefail
arch="${1:-x86_64}"
[ $# -gt 0 ] && shift
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
tools="${GT4_LINUX_TOOLS:-$HOME/.cache/gt4-native/linux-tools}"
case "$arch" in
    x86_64)  deb=amd64; short=x64;   mirror=http://archive.ubuntu.com/ubuntu ;;
    aarch64) deb=arm64; short=arm64; mirror=http://ports.ubuntu.com/ubuntu-ports ;;
    *) echo "usage: bash tools/build_linux.sh [x86_64|aarch64] [CMake arguments]" >&2; exit 2 ;;
esac
[ "$(uname -m)" = x86_64 ] || { echo "build_linux.sh runs on an x86_64 machine (its zig and wayland-scanner)" >&2; exit 2; }
build="${GT4_LINUX_BUILD:-$root/build/host-linux-$short-Release}"
mkdir -p "$tools"

# zig 0.17.1 for this machine (https://ziglang.org/download/index.json)
zig_dir="$tools/zig-x86_64-linux-0.17.1"
if [ ! -x "$zig_dir/zig" ]; then
    echo "fetching zig 0.17.1"
    curl -sSfLo "$tools/zig.tar.xz" https://ziglang.org/download/0.17.1/zig-x86_64-linux-0.17.1.tar.xz
    echo "3581863e3cbcfd0fce0efc682ce7e9e93da96668a977791d356a26d2a7e9b17a  $tools/zig.tar.xz" | sha256sum -c --quiet
    tar -xf "$tools/zig.tar.xz" -C "$tools" && rm "$tools/zig.tar.xz"
fi
export ZIG_GLOBAL_CACHE_DIR="$tools/zig-cache" ZIG_LOCAL_CACHE_DIR="$tools/zig-cache"

# A private apt for Ubuntu noble's packages of one architecture: download only, nothing installed.
apt_for() {   # deb-architecture mirror -> sets apt_opts
    local a="$tools/apt-$1"
    mkdir -p "$a/state/lists/partial" "$a/cache/archives/partial" "$a/etc/apt.conf.d" "$a/etc/preferences.d" "$a/debs"
    local key=/usr/share/keyrings/ubuntu-archive-keyring.gpg
    printf 'deb [arch=%s signed-by=%s] %s %s main universe\n' "$1" "$key" "$2" noble "$1" "$key" "$2" noble-updates \
        "$1" "$key" "$2" noble-security > "$a/etc/sources.list"
    apt_opts=(-o "Dir::State=$a/state" -o "Dir::Cache=$a/cache" -o "Dir::Etc=$a/etc"
              -o "Dir::Etc::SourceList=$a/etc/sources.list" -o "Dir::Etc::SourceParts=-" -o "APT::Architecture=$1"
              -o "APT::Architectures::=$1" -o "Debug::NoLocking=1")
    apt_debs="$a/debs"
    [ -n "$(ls "$a/state/lists" 2>/dev/null | grep -v partial)" ] || apt-get "${apt_opts[@]}" update -qq
}
fetch() {   # architecture packages...: into apt_debs, each once
    local a="$1"; shift
    (cd "$apt_debs" && for p in "$@"; do
        ls "${p}"_*_"$a".deb "${p}"_*_all.deb >/dev/null 2>&1 && continue
        # (lists cached by an earlier run can name versions the mirror has dropped since: refreshed once, then again)
        apt-get "${apt_opts[@]}" download -qq "$p:$a" ||
            { apt-get "${apt_opts[@]}" update -qq && apt-get "${apt_opts[@]}" download -qq "$p:$a"; }
    done)
}

# wayland-scanner, for this machine
if [ ! -x "$tools/wayland-scanner/usr/bin/wayland-scanner" ]; then
    apt_for amd64 http://archive.ubuntu.com/ubuntu
    fetch amd64 libwayland-bin
    dpkg-deb -x "$apt_debs"/libwayland-bin_*.deb "$tools/wayland-scanner"
fi

# The backends' sysroot for ARCH
sysroot="$tools/sysroot-$arch"
packages="libasound2-dev libasound2t64 libdbus-1-dev libdbus-1-3 libdecor-0-dev libdecor-0-0 libpipewire-0.3-dev
    libpipewire-0.3-0t64 libpulse-dev libpulse0 libspa-0.2-dev libudev-dev libudev1 libwayland-dev libwayland-client0
    libwayland-cursor0 libwayland-egl1 libwayland-server0 libffi-dev libffi8 libx11-dev libx11-6 libxau-dev libxcb1-dev
    libxcb1 libxcursor-dev libxcursor1 libxdmcp-dev libxext-dev libxext6 libxfixes-dev libxfixes3 libxi-dev libxi6
    libxkbcommon-dev libxkbcommon0 libxrandr-dev libxrandr2 libxrender-dev libxrender1 libxss-dev libxss1 libxtst-dev
    libxtst6 wayland-protocols x11proto-dev libegl-dev libegl1 libgl-dev libglx-dev libgles-dev libopengl-dev"
if [ ! -f "$sysroot/PACKAGES" ]; then
    echo "making the $arch sysroot (Ubuntu noble's $deb packages)"
    apt_for "$deb" "$mirror"
    # shellcheck disable=SC2086
    fetch "$deb" $packages
    rm -rf "$sysroot.part" && mkdir -p "$sysroot.part"
    for d in "$apt_debs"/*.deb; do dpkg-deb -x "$d" "$sysroot.part"; done
    # absolute links (libfoo.so -> /lib/...) made to point inside the sysroot
    find "$sysroot.part" -type l -lname '/*' | while read -r l; do ln -sfn "$sysroot$(readlink "$l")" "$l"; done
    (cd "$apt_debs" && ls ./*.deb | sed 's#^\./##') > "$sysroot.part/PACKAGES"
    rm -rf "$sysroot" && mv "$sysroot.part" "$sysroot"
fi

# zig as CMake's compilers (one executable each), and the toolchain
wrap="$tools/zig-$arch"
mkdir -p "$wrap"
for t in cc c++; do printf '#!/bin/sh\nexec "%s" %s -target %s-linux-gnu.2.35 "$@"\n' "$zig_dir/zig" "$t" "$arch" > "$wrap/zig-$t"; done
for t in ar ranlib; do printf '#!/bin/sh\nexec "%s" %s "$@"\n' "$zig_dir/zig" "$t" > "$wrap/zig-$t"; done
chmod +x "$wrap"/zig-*
cross=()
[ "$arch" = aarch64 ] && cross=(-DCMAKE_SYSTEM_NAME=Linux -DCMAKE_SYSTEM_PROCESSOR=aarch64)
cat > "$wrap/toolchain.cmake" <<EOF
set(CMAKE_C_COMPILER "$wrap/zig-cc")
set(CMAKE_CXX_COMPILER "$wrap/zig-c++")
set(CMAKE_AR "$wrap/zig-ar")
set(CMAKE_RANLIB "$wrap/zig-ranlib")
set(CMAKE_FIND_ROOT_PATH "$sysroot")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
set(CMAKE_LIBRARY_ARCHITECTURE $arch-linux-gnu)
# the backends' headers after zig's own (its glibc 2.35 first); SDL's header checks do not search the root path
set(CMAKE_C_FLAGS_INIT "-idirafter $sysroot/usr/include -idirafter $sysroot/usr/include/$arch-linux-gnu")
set(CMAKE_CXX_FLAGS_INIT "-idirafter $sysroot/usr/include -idirafter $sysroot/usr/include/$arch-linux-gnu")
EOF
export PKG_CONFIG_SYSROOT_DIR="$sysroot"
export PKG_CONFIG_LIBDIR="$sysroot/usr/lib/$arch-linux-gnu/pkgconfig:$sysroot/usr/share/pkgconfig"
export PKG_CONFIG_PATH=
export PATH="$tools/wayland-scanner/usr/bin:$PATH"
export LD_LIBRARY_PATH="$tools/wayland-scanner/usr/lib/x86_64-linux-gnu${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

glslang=()
if [ "$arch" = aarch64 ]; then
    shaders="${GT4_GLSLANG_EXECUTABLE:-}"
    if [ -z "$shaders" ]; then   # the x86_64 build's glslang, built if needed
        native="${GT4_LINUX_NATIVE_BUILD:-$(dirname "$build")/host-linux-x64-Release}"
        [ -f "$native/build.ninja" ] || GT4_LINUX_BUILD="$native" bash "$0" x86_64 -DBUILD_TESTING=OFF --configure-only
        cmake --build "$native" --target glslang-standalone
        shaders="$(find "$native/_deps" -type f -name glslang -perm -u+x | head -1)"
    fi
    glslang=("-DGT4_GLSLANG_EXECUTABLE=$shaders")
fi

configure_only=0
args=()
for a in "$@"; do [ "$a" = --configure-only ] && configure_only=1 || args+=("$a"); done
testing=ON
[ "$arch" = aarch64 ] && testing=OFF
cd "$root"
cmake -S . -B "$build" -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_TOOLCHAIN_FILE="$wrap/toolchain.cmake" \
    -DGT4_BUILD_HOST=ON -DBUILD_TESTING=$testing "${cross[@]}" "${glslang[@]}" "${args[@]}"
[ $configure_only = 1 ] && exit 0
cmake --build "$build" --parallel "${GT4_JOBS:-$(nproc)}"
# what the package checks: the architecture, and no glibc symbol version above 2.35
readelf -h "$build/gt4_host" | grep -E 'Machine'
newest="$(readelf -V "$build/gt4_host" | grep -o 'GLIBC_2\.[0-9.]*' | sort -uV | tail -1)"
echo "gt4_host needs $newest at most; $(readelf -d "$build/gt4_host" | grep -c NEEDED) libraries: $(readelf -d "$build/gt4_host" | grep -o '\[lib[^]]*\]' | tr -d '[]' | tr '\n' ' ')"
case "$newest" in GLIBC_2.3[6-9]*|GLIBC_2.[4-9]*) echo "needs a glibc newer than 2.35" >&2; exit 1 ;; esac
[ "$testing" = ON ] && ctest --test-dir "$build" --output-on-failure
echo "Built $build/gt4_host"
